created = 0
updated = 0
skipped = 0
errors = 0

for old_uuid, scores_data in RECOVERED_SCORES.items():
    anon_id = OLD_TO_ANON.get(old_uuid)
    if not anon_id:
        print(f"ERROR: No mapping for {old_uuid}")
        errors += 1
        continue

    copy = Copy.objects.filter(anonymous_id=anon_id).first()
    if not copy:
        print(f"ERROR: No copy found for {anon_id}")
        errors += 1
        continue

    # Check if copy is assigned to Patrick
    if copy.assigned_corrector_id != patrick.id:
        print(f"WARNING: {anon_id} is assigned to user {copy.assigned_corrector_id}, not Patrick ({patrick.id})")

    # Calculate total
    total = sum(v for v in scores_data.values() if isinstance(v, (int, float)))
    total = round(total, 2)

    # Check existing score
    existing = Score.objects.filter(copy=copy).first()
    if existing:
        old_total = sum(v for v in existing.scores_data.values() if isinstance(v, (int, float))) if existing.scores_data else 0
        old_total = round(old_total, 2)
        print(f"  {anon_id} ({copy.id}): EXISTING score total={old_total}/20 -> RECOVERED total={total}/20")
        if not DRY_RUN:
            existing.scores_data = scores_data
            existing.save()
        updated += 1
    else:
        print(f"  {anon_id} ({copy.id}): NEW score total={total}/20")
        if not DRY_RUN:
            Score.objects.create(copy=copy, scores_data=scores_data, final_comment='')
        created += 1

print(f"\n{'='*60}")
