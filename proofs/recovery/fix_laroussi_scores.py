from exams.models import Copy
from grading.models import Score, GradingEvent
from django.contrib.auth import get_user_model

User = get_user_model()
laroussi = User.objects.get(username="laroussi.laroussi@ert.tn")

fixed = 0
skipped = 0
errors = []

print("=" * 70)
print("FIX SCORES LAROUSSI — Raw localStorage (correcting corrupted import)")
print(f"Date: {datetime.now().isoformat()}")
print(f"Corrector: {laroussi.username}")
