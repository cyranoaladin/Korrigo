for anon_id in sorted(SCORES_RAW.keys()):
    raw_scores = SCORES_RAW[anon_id]
    raw_total = sum(float(v) for v in raw_scores.values())
    raw_nq = len(raw_scores)

    try:
        copy = Copy.objects.get(anonymous_id=anon_id)
    except Copy.DoesNotExist:
        errors.append(f"{anon_id}: Copy NOT FOUND")
        print(f"  ERROR {anon_id}: Copy not found in DB")
        continue

    existing = Score.objects.filter(copy=copy).first()
    if existing and existing.scores_data:
        old_total = sum(float(v) for v in existing.scores_data.values() if v is not None and v != "")
        old_nq = len(existing.scores_data)

        # Compare
        diffs = 0
        for k in set(list(raw_scores.keys()) + list(existing.scores_data.keys())):
            rv = raw_scores.get(k, "MISS")
            ev = existing.scores_data.get(k, "MISS")
            if str(rv) != str(ev):
                diffs += 1

        if diffs == 0:
            skipped += 1
            print(f"  SKIP  {anon_id}: already correct ({raw_nq}q, total={raw_total:.2f})")
            continue

        # Update with raw scores
        existing.scores_data = raw_scores
        existing.save()
        fixed += 1
        print(f"  FIX   {anon_id}: {diffs} values corrected | old_total={old_total:.2f} -> new_total={raw_total:.2f} | {old_nq}q -> {raw_nq}q")
    else:
        # Create (shouldn't happen but just in case)
        Score.objects.create(copy=copy, scores_data=raw_scores)
        fixed += 1
        print(f"  CREATE {anon_id}: {raw_nq}q, total={raw_total:.2f}")

    # Log grading event
    GradingEvent.objects.create(
        copy=copy,
        actor=laroussi,
        action="ls_fix",
        metadata={
            "source": "fix_laroussi_scores.py",
            "reason": "corrupted import_laroussi_scores.py had wrong per-question values",
            "raw_total": round(raw_total, 2),
            "nq": raw_nq,
            "fixed_at": datetime.now().isoformat(),
        }
    )

print()
print("=" * 70)
print(f"RESULTS: fixed={fixed}, skipped={skipped}, errors={len(errors)}")
if errors:
    print(f"Errors: {errors}")
